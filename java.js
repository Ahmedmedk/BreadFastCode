
function search() {
    let searchBar = document.querySelector('.Search-input').value.toUpperCase();

    let cards = document.querySelectorAll('.card');

    cards.forEach(card => {
        let productName = card.querySelector('.card-title').textContent.toUpperCase();

        if (productName.includes(searchBar)) {
            card.style.display = "";
        } else {
            card.style.display = "none";
        }
    });
}





function copyParagraphText() {
  // 1. Grab the inner text of the target element
  const text = document.getElementById("textToCopy").innerText;

  // 2. Directly write the text string to the clipboard
  navigator.clipboard.writeText(text)
    .then(() => {
      alert("Paragraph text copied successfully!");
    })
    .catch(err => {
      console.error("Could not copy text: ", err);
    });
}

